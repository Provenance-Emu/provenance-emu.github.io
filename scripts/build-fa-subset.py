#!/usr/bin/env python3
"""
build-fa-subset.py

Builds a self-hosted Font Awesome Free subset containing only the icons the
site actually references, replacing the ~270 KB of webfonts pulled from cdnjs.

Re-run this whenever you add or change a `fa-*` icon in a template, data file,
content file or script — icons not in the subset render as blank boxes.

Requirements (once):
  python3 -m venv .venv && .venv/bin/pip install fonttools brotli

Usage:
  .venv/bin/python scripts/build-fa-subset.py

Output (commit both):
  static/plugins/fontawesome/css/fontawesome.min.css
  static/plugins/fontawesome/webfonts/fa-{solid-900,regular-400,brands-400}.woff2
"""

import re
import sys
import tempfile
import urllib.request
from pathlib import Path

from fontTools import subset

FA_VERSION = "6.5.1"
CDN = f"https://cdnjs.cloudflare.com/ajax/libs/font-awesome/{FA_VERSION}"
FONTS = ["fa-solid-900", "fa-regular-400", "fa-brands-400"]

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "static" / "plugins" / "fontawesome"

# Everything that can name an icon. Vendored plugin bundles are skipped.
SCAN = [
    "config.toml",
    "content",
    "data",
    "layouts",
    "static/js",
    "themes/provenance-dark/layouts",
    "themes/small-apps-prov/layouts",
    "themes/small-apps-prov/assets",
    "themes/small-apps-prov/static/js",
]
SCAN_EXT = {".html", ".md", ".yml", ".yaml", ".toml", ".json", ".js", ".scss", ".css"}

ICON_SELECTOR = re.compile(r"^\.(fa-[a-z0-9-]+)::?before$")


def used_tokens():
    tokens = set()
    for entry in SCAN:
        path = ROOT / entry
        files = [path] if path.is_file() else (p for p in path.rglob("*") if p.suffix in SCAN_EXT)
        for f in files:
            tokens.update(re.findall(r"\bfa-[a-z0-9-]+", f.read_text(errors="ignore")))
    return tokens


def top_level_blocks(css):
    """Split minified CSS into top-level `prelude{body}` blocks (handles nested @keyframes)."""
    blocks, depth, start = [], 0, 0
    for i, ch in enumerate(css):
        if ch == "{":
            depth += 1
        elif ch == "}":
            depth -= 1
            if depth == 0:
                blocks.append(css[start : i + 1])
                start = i + 1
    return blocks


def main():
    tokens = used_tokens()
    with tempfile.TemporaryDirectory() as tmp:
        tmp = Path(tmp)
        for name in ["css/all.min.css"] + [f"webfonts/{f}.woff2" for f in FONTS]:
            urllib.request.urlretrieve(f"{CDN}/{name}", tmp / Path(name).name)

        css = (tmp / "all.min.css").read_text()
        banner = re.match(r"/\*!.*?\*/", css, re.S).group(0)
        blocks = top_level_blocks(css[len(banner):])

        kept, used_icons, codepoints = [], set(), set()
        for block in blocks:
            prelude, body = block.split("{", 1)
            prelude = prelude.strip()  # all.min.css has stray newlines between some rules
            if prelude.startswith("@font-face"):
                # Drop the v4-compat "FontAwesome" faces; nothing on the site uses that family.
                if '"FontAwesome"' in body:
                    continue
                body = re.sub(r",url\([^)]*\.ttf\) format\(\"truetype\"\)", "", body)
                kept.append(prelude + "{" + body)
                continue
            selectors = prelude.split(",")
            icon_names = [ICON_SELECTOR.match(s) for s in selectors]
            if all(icon_names):
                wanted = [s for s, m in zip(selectors, icon_names) if m.group(1) in tokens]
                if not wanted:
                    continue
                used_icons.update(m.group(1) for m in icon_names if m.group(1) in tokens)
                cp = re.search(r'content:"\\([0-9a-f]+)"', body)
                if cp:
                    codepoints.add(int(cp.group(1), 16))
                kept.append(",".join(wanted) + "{" + body)
            else:
                kept.append(block)

        (OUT / "css").mkdir(parents=True, exist_ok=True)
        (OUT / "webfonts").mkdir(parents=True, exist_ok=True)
        header = f"/* Generated by scripts/build-fa-subset.py — do not edit; re-run the script. */\n"
        (OUT / "css" / "fontawesome.min.css").write_text(header + banner + "".join(kept) + "\n")

        opts = subset.Options()
        opts.flavor = "woff2"
        opts.layout_features = []  # icon ligatures aren't used
        opts.hinting = False
        for font in FONTS:
            f = subset.load_font(str(tmp / f"{font}.woff2"), opts)
            s = subset.Subsetter(opts)
            s.populate(unicodes=codepoints)
            s.subset(f)
            subset.save_font(f, str(OUT / "webfonts" / f"{font}.woff2"), opts)

    unknown = sorted(t for t in tokens if t not in used_icons)
    print(f"{len(used_icons)} icons, {len(codepoints)} glyphs")
    for p in sorted(OUT.rglob("*.*")):
        print(f"  {p.relative_to(ROOT)}  {p.stat().st_size / 1024:.1f} KB")
    print("fa-* tokens that are not icons (utilities like fa-2x, or typos):", ", ".join(unknown) or "none")


if __name__ == "__main__":
    sys.exit(main())
